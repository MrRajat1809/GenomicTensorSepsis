def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def stream_digest(stream, algorithm="sha256"):
    digest = hashlib.new(algorithm)
    for block in iter(lambda: stream.read(4 * 1024 * 1024), b""):
        digest.update(block)
    return digest.hexdigest()


def file_record(path):
    with Path(path).open("rb") as stream:
        return dict(sha256=stream_digest(stream), size_bytes=Path(path).stat().st_size)


def md5(path):
    with Path(path).open("rb") as stream:
        return stream_digest(stream, "md5")


def project_path(name):
    path = (ROOT / name).resolve()
    require(path.is_relative_to(ROOT), f"Path outside project: {name}")
    return path


def validate_inputs():
    """Confirm that every stage passed its quality control with unchanged code and receipts, and return the files that the receipts bind."""
    bound, quality, inputs = {}, {}, {}
    for number, (stage, verdict) in STAGES.items():
        report = ROOT / "outputs" / stage / "qc.json"
        require(report.is_file(), f"Stage {number} ({stage}) has no quality-control report; run the stage first")
        qc = read_json(report)
        require(qc.get("status") == "PASS" and qc.get("failures") == 0 and qc.get("eligibility") == verdict,
                f"Stage {number} ({stage}) has not passed its quality control; rerun it before exporting")
        for name, expected in {**qc["code"], **qc["dependencies"]}.items():
            require(project_path(name).is_file() and file_record(project_path(name)) == expected,
                    f"Changed since the quality control of stage {number} ({stage}): {name}")
        for name, expected in qc["dependencies"].items():
            receipt = read_json(project_path(name))
            require(receipt.get("status") == "COMPLETE", f"Incomplete receipt: {name}")
            bound.update(receipt.get("outputs", {}))
            inputs[name] = expected
        inputs[report.relative_to(ROOT).as_posix()] = file_record(report)
        quality[stage] = {key: qc[key] for key in ("status", "required_checks", "failures", "eligibility", "generated_at_utc")}
        quality[stage]["configuration"] = sorted(name for name in qc["code"] if name.endswith(".json"))
    return bound, quality, inputs


def bound_table(name, bound, columns=None):
    """Read a stage table after confirming that it is the file its stage receipt binds."""
    import pandas as pd

    relative = f"{PROCESSED}/{name}"
    require(relative in bound and file_record(project_path(relative)) == bound[relative], f"Not the output of a completed stage: {relative}")
    return pd.read_parquet(project_path(relative), columns=columns)


def kind_of(dtype):
    import pandas as pd

    if pd.api.types.is_bool_dtype(dtype):
        return "boolean"
    if pd.api.types.is_integer_dtype(dtype):
        return "integer"
    return "number" if pd.api.types.is_float_dtype(dtype) else "string"


def describe(table, frame):
    """Return the dictionary entry of every column of a table; a column without a written description stops the export."""
    fields = []
    for name in frame.columns:
        description = DOC.get(f"{table}.{name}", DOC.get(name))
        require(description, f"Released column has no description: {table}.{name}")
        kind, values, allowed = kind_of(frame[name].dtype), frame[name], ""
        missing = "empty field" if values.isna().any() else "not permitted"
        if kind == "boolean":
            allowed = "0; 1"
        elif kind == "string":
            distinct = sorted(set(values.dropna().astype(str)) - {""})
            missing = "empty field" if values.isna().any() or (values == "").any() else "not permitted"
            allowed = json.dumps(distinct, ensure_ascii=False) if len(distinct) <= ENUMERATED and len(values) >= 50 else ""
        fields.append(dict(column=name, type=kind, unit=UNITS.get(name, ""), description=description, missing_value=missing, allowed_values=allowed))
    return fields


def write_frame(frame, path):
    """Write a table as deterministic gzip-compressed CSV: booleans as 0 and 1, a missing value as an empty field."""
    import numpy as np

    logical = [name for name in frame.columns if frame[name].dtype == bool]
    if logical:
        frame = frame.astype({name: "int8" for name in logical})
    for name in frame.select_dtypes("floating").columns:
        require(not np.isinf(frame[name].to_numpy()).any(), f"Infinite value cannot be released: {path.name} {name}")
    with path.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=6) as compressed:
            with io.TextIOWrapper(compressed, encoding="utf-8", newline="") as text:
                frame.to_csv(text, index=False, lineterminator="\n")


def convert(job):
    """Write one per-study table as CSV.gz in a worker process, after confirming that it is the file its stage receipt binds."""
    import pandas as pd

    source, expected, target = job
    require(file_record(source) == expected, f"Not the output of a completed stage: {source}")
    frame = pd.read_parquet(source)
    write_frame(frame, Path(target))
    return dict(rows=len(frame), columns=[str(name) for name in frame.columns], types=[kind_of(dtype) for dtype in frame.dtypes])


class Archive:
    """Collect deterministic members in one tar archive (no times, owners or permissions of this machine); see COMPRESSED for which are gzip-compressed."""
    def __init__(self, folder, name, dictionary, records):
        self.folder, self.name, self.filename = folder, name, ARCHIVE_FILES[name]
        self.dictionary, self.records = dictionary, records
        self.raw = (folder / self.filename).open("wb")
        self.compressed = gzip.GzipFile(filename="", mode="wb", fileobj=self.raw, mtime=0, compresslevel=6) if name in COMPRESSED else None
        self.tar = tarfile.open(fileobj=self.compressed or self.raw, mode="w", format=tarfile.PAX_FORMAT)

    def add(self, filename, path):
        require(VALID_NAME.fullmatch(filename) and ".." not in filename.split("/"), f"Member name outside the portable characters: {filename}")
        info = tarfile.TarInfo(filename)
        info.size, info.mtime, info.mode = Path(path).stat().st_size, 0, 0o644
        with Path(path).open("rb") as source:
            self.tar.addfile(info, source)

    def member(self, filename, path, description, row_unit, keys, fields, rows, names):
        """Add one CSV.gz table with its dictionary entries: one for every named column, in order, and at most one for all the sample columns after them."""
        named = [entry["column"] for entry in fields if not entry["column"].startswith("<")]
        require(named == list(names[:len(named)]) and len(fields) - len(named) == int(len(named) < len(names)),
                f"Every column of {filename} needs its entry in the data dictionary")
        self.add(filename, path)
        self.records[f"{self.filename}/{filename}"] = dict(**file_record(path), rows=rows, columns=len(names))
        self.dictionary.extend(dict(archive=self.filename, file=filename, file_description=description, row_unit=row_unit, key_columns=keys,
                                    position=position, **entry) for position, entry in enumerate(fields))
        path.unlink()
        print(f"[EXPORT] {self.name}/{filename}: {rows:,} rows, {len(names):,} columns", flush=True)

    def table(self, name, frame, description, row_unit, keys):
        filename = f"{self.name}_{name}.csv.gz"
        require(not frame.columns.duplicated().any(), f"Duplicate columns in {filename}")
        write_frame(frame, self.folder / filename)
        self.member(filename, self.folder / filename, description, row_unit, keys, describe(name, frame), len(frame), list(frame.columns))

    def file(self, filename, path):
        self.add(filename, path)
        self.records[f"{self.filename}/{filename}"] = file_record(path)

    def close(self):
        self.tar.close()
        if self.compressed is not None:
            self.compressed.close()
        self.raw.close()


