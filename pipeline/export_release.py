def code_version():
    """The commit that the repository checks out, read from its .git folder; empty where it has none."""
    head = ROOT / ".git" / "HEAD"
    if not head.is_file():
        return dict(commit="", branch="")
    text = head.read_text(encoding="utf-8").strip()
    if not text.startswith("ref: "):
        return dict(commit=text, branch="")
    ref = text[5:]
    loose = ROOT / ".git" / ref
    if loose.is_file():
        return dict(commit=loose.read_text(encoding="utf-8").strip(), branch=ref.rsplit("/", 1)[-1])
    packed = ROOT / ".git" / "packed-refs"
    found = [line.split(" ", 1)[0] for line in (packed.read_text(encoding="utf-8").splitlines() if packed.is_file() else []) if line.endswith(" " + ref)]
    return dict(commit=found[0] if found else "", branch=ref.rsplit("/", 1)[-1])


