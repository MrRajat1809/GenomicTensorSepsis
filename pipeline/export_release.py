def study_platform_table(bound):
    """Join what describes one study platform: its counts by class, how its values were processed, and the names of its tables in this release."""
    table = bound_table("cohort/cohort_summary.parquet", bound)
    index = bound_table("annotation/matrix_index.parquet", bound, ["accession", "platform", "platform_title", "family", "method", "features", "reason"])
    genes = bound_table("annotation/gene_matrix_summary.parquet", bound, ["accession", "platform", "genes", "protein_coding_genes", "rule"])
    keys = ["study_accession", "platform"]
    table = table.merge(index.rename(columns={"accession": "study_accession"}), on=keys, how="left", validate="one_to_one")
    require(table["family"].notna().all() and (table["reason"] == "").all(), "Every study platform of the cohort summary must have an expression table")
    table = table.drop(columns="reason")
    table = table.merge(genes.rename(columns={"accession": "study_accession", "rule": "gene_rule"}), on=keys, how="left", validate="one_to_one")
    table[["genes", "protein_coding_genes"]] = table[["genes", "protein_coding_genes"]].astype("Int64")
    table["gene_rule"] = table["gene_rule"].fillna("")
    folders = ([(f"{archive}_file", archive, folder) for archive, folder, *_ in LAYERS]
               + [(f"{name}_file", f"gene_mapping_{name}", folder) for name, folder, *_ in MAPS])
    for column, prefix, folder in folders:
        table[column] = [f"{prefix}_{study}__{platform}.csv.gz" if (ROOT / PROCESSED / folder / f"{study}__{platform}.parquet").is_file() else ""
                         for study, platform in zip(table["study_accession"], table["platform"])]
    first = ["cohort_group", "source", "study_accession", "platform", "platform_title", "family", "method", "value_scale", "features", "genes",
             "protein_coding_genes", "gene_rule"]
    last = ["release_date", "shares_samples_with", *(column for column, _, _ in folders)]
    return table[first + [name for name in table.columns if name not in first + last] + last]


