def cohort_flow(bound):
    """Count the records from the searches of the repositories to the samples of the resource, for the resource and for every study platform."""
    census = bound_table("acquisition/census.parquet", bound, ["census_status"])
    decisions = bound_table("acquisition/study_decisions.parquet", bound, ["decision", "reason"])
    index = bound_table("annotation/sample_index.parquet", bound, ["study_accession", "sample_accession", "in_matrix", "reason"])
    samples = bound_table("cohort/cohort_samples.parquet", bound)
    without = bound_table("cohort/records_without_values.parquet", bound, ["study_accession", "sample_accession", "platform", "reason"])
    ledger = bound_table("correction/correction_ledger.parquet", bound)
    require(len(ledger) == len(samples), "The correction ledger and the cohort table must hold the same records")
    # The included records are those with expression values, in the cohort table, and those without, in their ledger with the reason of the sample index.
    keyed = lambda frame, *names: set(zip(frame["study_accession"], frame["sample_accession"], *(frame[name] for name in names)))
    require(len(index) == len(samples) + len(without) and keyed(index[index["in_matrix"]]) == keyed(samples)
            and keyed(index[~index["in_matrix"]], "reason") == keyed(without, "reason"),
            "The sample index must hold exactly the records of the cohort table and those of the ledger of records without values")
    counted = ledger[ledger["is_primary_record"]]
    outcomes = {"resource": counted, **{f"{study}|{platform}": part for (study, platform), part in counted.groupby(["study_accession", "platform"])}}
    # Every record of the bulk-blood study units is in the aligned table. A record of another group is counted as that group (pbmc_group); any other record
    # outside the table keeps the reason of the correction stage.
    records = bound_table("correction/correction_records.parquet", bound, ["study_accession", "sample_accession", "platform", "group", "status", "reason"])
    require(len(records) == len(samples) and keyed(records) == keyed(samples), "The records of the correction stage must be those of the cohort table")
    records["in_aligned"] = (records["group"] == ALIGNED) & (records["status"] == "in_unit")
    other = ~records["group"].isin(["", ALIGNED])
    records["outside"] = (records["group"] + "_group").where(other, records["reason"]).where(~records["in_aligned"], "")
    require(not records.loc[~records["in_aligned"], "outside"].isin(["", "_group"]).any(), "Every record outside the aligned table needs a reason")
    aligned = {"resource": records, **{f"{study}|{platform}": part for (study, platform), part in records.groupby(["study_accession", "platform"])}}
    naive = bound_table("benchmark/model_records.parquet", bound, ["task", "in_gts", "has_values", "reason"])
    tasks = bound_table("cohort/benchmark_tasks.parquet", bound, ["task", "eligible"])
    eligible = tasks.groupby("task")["eligible"].sum()
    require(set(naive["task"]) == set(eligible.index), "The benchmark must cover exactly the tasks of the cohort stage")
    for task, part in naive.groupby("task"):
        require(int(part["in_gts"].sum()) == int(eligible[task]), f"Every sample of task {task} must be in its naive population")
    rows = []

    def add(scope, stage, kind, step, description, population, denominator, count, note=""):
        rows.append(dict(scope=scope, stage=stage, kind=kind, step=step, step_description=description, denominator_population=population,
                         denominator=int(denominator), count=int(count), excluded=int(denominator - count) if kind == "selection" else None, note=note))

    candidates = int((census["census_status"] == "candidate").sum())
    included = int((decisions["decision"] == "include").sum())
    add("resource", "01", "selection", "records_found", "Records that the searches of the repositories returned.", "all search results", len(census), len(census))
    add("resource", "01", "selection", "candidate_studies", "Search results kept as candidate studies after the census.", "all search results", len(census),
        candidates)
    for reason, count in census.loc[census["census_status"] != "candidate", "census_status"].value_counts().sort_index().items():
        add("resource", "01", "reason", reason, "Search results not kept as candidates, by census outcome.", "all search results", len(census), count)
    require(candidates == len(decisions), "Every candidate study must have one screening decision")
    add("resource", "01", "selection", "included_studies", "Candidate studies included after screening of their records.", "candidate studies", candidates, included)
    for reason, count in decisions.loc[decisions["decision"] != "include", "reason"].value_counts().sort_index().items():
        add("resource", "01", "reason", reason, "Candidate studies excluded, by the first reason that applies.", "candidate studies", candidates, count)
    # Every study platform of the included studies is a scope, also one whose records all lack values.
    with_values = dict(list(samples.groupby(["study_accession", "platform"], sort=True)))
    missing = dict(list(without.groupby(["study_accession", "platform"], sort=True)))
    scopes = [("resource", samples, without)] + [(f"{study}|{platform}", with_values.get((study, platform), samples.iloc[0:0]),
                                                  missing.get((study, platform), without.iloc[0:0])) for study, platform in sorted(set(with_values) | set(missing))]
    for scope, part, absent in scopes:
        whole = scope == "resource"
        first, included = part[part["is_primary_record"]], len(part) + len(absent)
        add(scope, "01", "selection", "included_sample_records", "Sample records of the included studies.", "sample records", included, included)
        if whole:
            for reason, count in absent["reason"].value_counts().sort_index().items():
                add(scope, "02", "reason", reason, "Sample records without expression values, by reason.", "sample records", included, count)
        add(scope, "02", "selection", "sample_records_with_values", "Sample records whose values are in an expression table.", "sample records", included,
            len(part), "the records without values are listed with their reason and recorded fields in provenance_records_without_values")
        add(scope, "04", "selection", "distinct_samples" if whole else "primary_records",
            "Distinct samples: each array or library counted once across the studies that deposit it." if whole else
            "Records that are the first deposit of their sample; the other records repeat a sample of an earlier study.", "sample records with values",
            len(part), len(first), "repeated records stay in the tables and are marked by is_primary_record")
        add(scope, "04", "selection", "one_sample_per_patient", "Samples marked as the one sample of their patient.", "distinct samples" if whole else
            "primary records", len(first), int(part["one_per_patient"].sum()), "upper bound on patients: a sample without a patient identifier counts as its own")
        for name in CLASSES:
            add(scope, "04", "class", name, "Distinct samples of this curated class." if whole else "Primary records of this curated class.",
                "distinct samples" if whole else "primary records", len(first), int((first["sample_class"] == name).sum()))
        if whole:
            for task, count in eligible.items():
                add(scope, "04", "selection", f"{task}:samples_of_the_task", "Samples of the benchmark task: primary records of the one sample of their "
                    "patient, without a quality flag, of the tissues, phases and two classes of the task (cohort_benchmark_tasks).", "sample records with values",
                    len(part), count)
        held = outcomes.get(scope, counted.iloc[0:0])
        require(len(held) == len(first), f"The correction ledger must hold every distinct sample of {scope}")
        add(scope, "06", "selection", "samples_in_a_corrected_table" if whole else "primary_records_in_a_corrected_table",
            "Of those, the samples in the corrected bulk-blood or PBMC table.", "distinct samples" if whole else "primary records", len(held),
            int((held["outcome"] == "in_corrected_table").sum()), "the others stay in the per-study tables; the reason of every record is in corrected_expression_ledger")
        if whole:
            for reason, count in held.loc[held["outcome"] != "in_corrected_table", "reason"].value_counts().sort_index().items():
                add(scope, "06", "reason", reason, "Distinct samples that are in no corrected table, by reason.", "distinct samples", len(held), count)
        own = aligned.get(scope, records.iloc[0:0])
        require(len(own) == len(part), f"The records of the correction stage must hold every sample record of {scope}")
        add(scope, "06", "selection", "records_in_the_aligned_bulk_blood_table", "Sample records in the aligned bulk-blood table: every record of the bulk-blood "
            "study units of the correction stage, repeat deposits included.", "sample records with values", len(own), int(own["in_aligned"].sum()),
            "the baseline models of the benchmark read this table")
        if not whole:
            continue
        for reason, count in own.loc[~own["in_aligned"], "outside"].value_counts().sort_index().items():
            add(scope, "06", "reason", f"not_aligned:{reason}", "Sample records outside the aligned bulk-blood table: pbmc_group for the records of the PBMC "
                "group, otherwise by the reason of the correction stage.", "sample records with values", len(own), count)
        for task, records_of_task in naive.groupby("task", sort=True):
            with_values = records_of_task[records_of_task["has_values"]]
            add(scope, "07", "selection", f"{task}:naive_records", "Records that a naive pooling takes for the task: every record of its tissues and two "
                "classes, with repeat deposits, flagged samples and every sample of a patient.", "sample records with values", len(part), len(records_of_task))
            add(scope, "07", "selection", f"{task}:naive_records_with_aligned_values", "Naive records of the task with values in the aligned bulk-blood table, "
                "which the baseline models read.", "naive records of the task", len(records_of_task), len(with_values))
            for reason, count in records_of_task.loc[~records_of_task["has_values"], "reason"].value_counts().sort_index().items():
                add(scope, "07", "reason", f"{task}:{reason}", "Naive records of the task without aligned values, by reason.", "naive records of the task",
                    len(records_of_task), count)
            add(scope, "07", "selection", f"{task}:samples_of_the_task_with_aligned_values", "Samples of the task with values in the aligned bulk-blood table, "
                "which the models of the patient-safe schemes read.", "samples of the task", int(eligible[task]),
                int((records_of_task["in_gts"] & records_of_task["has_values"]).sum()))
    require(len({(row["scope"], row["stage"], row["kind"], row["step"]) for row in rows}) == len(rows), "Every count of the cohort flow needs its own step")
    return rows


