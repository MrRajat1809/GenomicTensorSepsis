def read_back(path, members):
    """Read every member of a written archive back and confirm its size and SHA-256 against the record made when it was added; return the member count."""
    expected = {key.split("/", 1)[1]: value for key, value in members.items() if key.split("/", 1)[0] == path.name}
    found = 0
    with tarfile.open(path, mode="r:*") as archive:
        for info in archive:
            entry = expected.get(info.name)
            require(info.isfile() and entry is not None and info.size == entry["size_bytes"], f"Unexpected member of {path.name}: {info.name}")
            require(stream_digest(archive.extractfile(info)) == entry["sha256"], f"Corrupt member of {path.name}: {info.name}")
            found += 1
    require(found == len(expected), f"Members missing from {path.name}")
    return found


def archive_layout(filename, names):
    """Describe the members of one archive for the readme: single tables by name, per-study tables and folders by their pattern and count."""
    groups, lines = {}, []
    for name in sorted(names):
        if "/" in name:
            key = name.split("/", 1)[0] + "/"
        elif "__" in name:
            key = name.split("__", 1)[0].rsplit("_", 1)[0] + "_<study_accession>__<platform>.csv.gz"
        else:
            lines.append(f"    {name}")
            continue
        groups[key] = groups.get(key, 0) + 1
    kinds = {True: ("file", "files"), False: ("table, one for every study platform", "tables, one for every study platform")}
    lines += [f"    {key}  ({count:,} {kinds[key.endswith('/')][count != 1]})" for key, count in sorted(groups.items())]
    return [f"{filename} ({len(names):,} members)", *lines]


